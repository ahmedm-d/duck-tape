import {expect, test} from '@playwright/test';

test('live Atlas reader serves public advisory and graph through the production UI', async ({page}, testInfo) => {
  test.skip(process.env.STEWARD_GLOBAL_LIVE_UI !== '1', 'Requires the explicitly configured live public Atlas reader and real public records.');
  test.setTimeout(90000);
  const errors: string[] = [];
  const requests: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (request.url().includes('/api/global-catalogue')) requests.push(request.url());
  });
  await page.goto('/#/global-catalogue');
  await expect(page.getByRole('heading', {name: 'Global catalogue', exact: true})).toBeVisible({timeout: 30000});
  await page.getByLabel('Catalogue store').selectOption('atlas');
  expect(requests).toHaveLength(0);
  await page.getByLabel('Ecosystem', {exact: true}).fill('PyPI');
  await page.getByLabel('Package', {exact: true}).fill('requests');
  const searchResponse = page.waitForResponse(response => response.url().includes('/api/global-catalogue?') && response.url().includes('provider=atlas'));
  await page.getByRole('button', {name: 'Search catalogue'}).click();
  const response = await searchResponse;
  expect(response.ok()).toBe(true);
  const result = await response.json();
  expect(result.provider).toBe('atlas');
  const entry = result.entries.find((item: {canonical_id: string}) => item.canonical_id === 'CVE-2024-35195');
  expect(entry).toBeTruthy();
  expect(entry.material_revision).toBe(1);
  expect(entry.source_quality).not.toBe('fixture');
  const card = page.locator('.global-catalogue-entries article').filter({hasText: 'CVE-2024-35195'});
  await expect(card.getByText('Version rules unsupported', {exact: true})).toBeVisible();
  await expect(card.getByRole('link', {name: 'Original source'})).toHaveAttribute('href', entry.source_url);
  await expect(page.getByText('Coverage unknown', {exact: true})).toBeVisible();
  const graphResponse = page.waitForResponse(response => response.url().includes('/api/global-catalogue/graph?') && response.url().includes('provider=atlas'));
  await page.getByRole('button', {name: 'View relationships'}).click();
  const graphResult = await graphResponse;
  expect(graphResult.ok()).toBe(true);
  const graph = await graphResult.json();
  expect(graph.nodes).toHaveLength(3);
  expect(graph.edges).toHaveLength(2);
  const graphView = page.getByRole('region', {name: 'Public relationship graph'});
  await expect(graphView.getByRole('status')).toContainText('3 nodes · 2 relationships');
  await expect(graphView.getByText('Version rules unsupported', {exact: true})).toHaveCount(2);
  await page.screenshot({path: testInfo.outputPath('live-atlas-catalogue-desktop.png'), fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  await page.getByRole('button', {name: 'Toggle theme'}).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path: testInfo.outputPath('live-atlas-catalogue-narrow-dark.png'), fullPage: true});
  await page.getByLabel('Package', {exact: true}).fill('duck-tape-unlisted-package');
  await page.getByRole('button', {name: 'Search catalogue'}).click();
  await expect(page.getByText('No catalogue entries found. This is not a clean scan.')).toBeVisible();
  await expect(page.getByText('Coverage unknown', {exact: true})).toBeVisible();
  expect(errors).toEqual([]);
});
